CREATE TABLE IF NOT EXISTS book_copies (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 book INT NOT NULL,
 accession VARCHAR(70) UNIQUE NOT NULL,
 condition_label VARCHAR(30) NOT NULL DEFAULT 'Good',
