CREATE TABLE IF NOT EXISTS fee_types (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(120) NOT NULL UNIQUE, amount DECIMAL(12,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS materials (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, offering INT NOT NULL, title VARCHAR(140) NOT NULL, url VARCHAR(1200) NOT NULL,
 FOREIGN KEY(offering) REFERENCES offerings(id)
);
CREATE TABLE IF NOT EXISTS marking_policy (
 offering INT PRIMARY KEY, coursework_weight INT NOT NULL, FOREIGN KEY(offering) REFERENCES offerings(id)
);
